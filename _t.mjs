import { chromium } from 'playwright';
const b = await chromium.launch(); const p = await b.newPage();
let navs=0, reqs={};
p.on('framenavigated', f=>{ if(f===p.mainFrame()) navs++; });
p.on('request', r=>{ const u=r.url().replace(/\?.*/,''); if(!u.includes('_next/static')) reqs[r.method()+' '+u]=(reqs[r.method()+' '+u]||0)+1; });
p.on('console', m=>{ if(m.type()==='error') console.log('console.error', m.text().slice(0,150)); });
await p.goto('https://lake-console-aulas-mackenzie.afonsolelis.tech/rustfs/console/', {waitUntil:'domcontentloaded'});
await p.waitForTimeout(5000);
console.log('antes do login: navs', navs, 'url', p.url());
